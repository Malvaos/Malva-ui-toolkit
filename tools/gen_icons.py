#!/usr/bin/env python3
"""Turns svg/icons, svg/app and svg/logo into the icon lookups of each language and the icon sheets.

    python3 tools/gen_icons.py            write
    python3 tools/gen_icons.py --check    exit 1 if anything on disk differs

Outputs (GENERATED, not to be edited):
    slint/icons.slint                Icon, AppIcon and Logo components (look an image up by name)
    cpp/include/malva/icons.h        name -> SVG text, for C++ code that is not using Slint
    rust/malva-icons/src/lib.rs      name -> SVG text, std only
    svg/icons-sheet.svg              every icon with its name, light and dark
    docs/ICONS.md                    the list"""
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
CHECK = "--check" in sys.argv
STALE = []
HEADER = "GENERATED by tools/gen_icons.py from svg/icons, svg/app and svg/logo. Do not edit by hand."


def out(path, text):
    full = os.path.join(ROOT, path)
    if CHECK:
        if not os.path.exists(full) or open(full).read() != text:
            STALE.append(path)
        return
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(text)


def load(sub):
    d = os.path.join(ROOT, "svg", sub)
    names = sorted(f[:-4] for f in os.listdir(d) if f.endswith(".svg"))  # by name, not by file name: "a" before "a-b"
    return {n: open(os.path.join(d, n + ".svg")).read().strip() for n in names}


icons, apps, logos = load("icons"), load("app"), load("logo")
LOGO_NAMES = ["malva-mark", "malva-mark-white", "malva-mark-black", "malva-wordmark", "malva-wordmark-white",
              "malva-logo-horizontal", "malva-logo-horizontal-reverse", "malva-logo-stacked", "malva-logo-stacked-reverse",
              "malva-app-icon", "malva-bloom"]
logos = {k: v for k, v in logos.items() if k in LOGO_NAMES}


# ------------------------------------------------------------------ Slint
def slint():
    L = [f"// {HEADER}", 'import { Theme, Size } from "tokens.slint";', "",
         "// A one-colour symbol, by name, tinted with `tint`. The names are the files of svg/icons.",
         "// An unknown name draws nothing. docs/ICONS.md lists them.",
         "export component Icon inherits Image {", "    in property <string> name;", "    in property <color> tint: Theme.text;",
         "    colorize: tint;", "    image-fit: contain;", "    width: Size.icon-m;", "    height: Size.icon-m;", "    source: name == \"\" ? @image-url(\"../svg/icons/more.svg\")"]
    for n in icons:
        L.append(f'        : name == "{n}" ? @image-url("../svg/icons/{n}.svg")')
    L.append('        : @image-url("../svg/icons/more.svg");')
    L.append("}")
    L += ["", "// A coloured application picture, by name (svg/app). Unknown names show \"default\".",
          "export component AppIcon inherits Image {", "    in property <string> name;", "    image-fit: contain;", "    width: 48px;", "    height: 48px;",
          '    source: name == "browser" ? @image-url("../svg/app/browser.svg")']
    for n in apps:
        if n != "browser":
            L.append(f'        : name == "{n}" ? @image-url("../svg/app/{n}.svg")')
    L.append('        : @image-url("../svg/app/default.svg");')
    L.append("}")
    L += ["", "// The Malva logo in one of its lock-ups (svg/logo): mark, wordmark, horizontal, stacked, bloom.",
          "// `reverse` picks the version for dark surfaces.",
          "export component Logo inherits Image {", '    in property <string> kind: "mark";', "    in property <bool> reverse: false;", "    image-fit: contain;",
          '    source: kind == "wordmark" ? (reverse ? @image-url("../svg/logo/malva-wordmark-white.svg") : @image-url("../svg/logo/malva-wordmark.svg"))',
          '        : kind == "horizontal" ? (reverse ? @image-url("../svg/logo/malva-logo-horizontal-reverse.svg") : @image-url("../svg/logo/malva-logo-horizontal.svg"))',
          '        : kind == "stacked" ? (reverse ? @image-url("../svg/logo/malva-logo-stacked-reverse.svg") : @image-url("../svg/logo/malva-logo-stacked.svg"))',
          '        : kind == "bloom" ? @image-url("../svg/logo/malva-bloom.svg")',
          '        : kind == "app" ? @image-url("../svg/logo/malva-app-icon.svg")',
          '        : (reverse ? @image-url("../svg/logo/malva-mark-white.svg") : @image-url("../svg/logo/malva-mark.svg"));', "}"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ C++
def cpp():
    def table(var, d):
        L = [f"inline constexpr std::array<Asset, {len(d)}> {var} = {{{{"]
        for k, v in d.items():
            assert ')svg"' not in v
            L.append(f'    {{"{k}", R"svg({v})svg"}},')
        L.append("}};")
        return L
    L = [f"// {HEADER}", "#pragma once", "#include <array>", "#include <string_view>", "", "namespace malva::icons {", "",
         "struct Asset {", "    std::string_view name;", "    std::string_view svg;", "};", "",
         "// One-colour symbols: stroke and fill are `currentColor`, so replace that word to colour one."]
    L += table("symbols", icons)
    L += ["", "// Coloured application pictures."] + table("apps", apps)
    L += ["", "// The brand lock-ups."] + table("logos", logos)
    L += ["", "template <class Table>", "constexpr std::string_view find(const Table& t, std::string_view name) {",
          "    for (const auto& a : t) {", "        if (a.name == name) return a.svg;", "    }", "    return {};", "}", "", "}  // namespace malva::icons"]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ Rust
def rust():
    def table(var, d):
        L = [f"pub const {var}: [(&str, &str); {len(d)}] = ["]
        for k, v in d.items():
            assert '"##' not in v
            L.append(f'    ("{k}", r##"{v}"##),')
        L.append("];")
        return L
    L = [f"// {HEADER}", "//! The Malva icon set as SVG text: no files to ship, no paths to resolve.", "",
         "/// One-colour symbols. Stroke and fill are `currentColor`; see [`svg_with_color`]."]
    L += table("SYMBOLS", icons)
    L += ["", "/// Coloured application pictures."] + table("APPS", apps)
    L += ["", "/// The brand lock-ups."] + table("LOGOS", logos)
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ sheet + docs
def inner(svg):
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    attrs = re.search(r"<svg([^>]*)>", svg).group(1)
    return attrs, m.group(1)


def sheet():
    cols, cw, chh, pad = 12, 104, 92, 28
    rows = (len(icons) + cols - 1) // cols
    W, H1 = cols * cw + 2 * pad, rows * chh + 120
    o = [f"<!-- {HEADER} -->", f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{W}" height="{H1 * 2}" viewBox="0 0 {W} {H1 * 2}" font-family="Inter, system-ui, sans-serif">']
    res = json.load(open(os.path.join(ROOT, "dist", "resolved.json")))
    sheet_modes = tuple((res[m]["bg"], res[m]["text"], res[m]["text-2"], m.capitalize()) for m in ("light", "dark"))
    for mi, (bg, fg, sub, title) in enumerate(sheet_modes):
        y0 = mi * H1
        o.append(f'<rect x="0" y="{y0}" width="{W}" height="{H1}" fill="{bg}"/>')
        o.append(f'<text x="{pad}" y="{y0 + 52}" font-size="24" font-weight="700" fill="{fg}">Malva icons — {title}</text>')
        o.append(f'<text x="{pad}" y="{y0 + 76}" font-size="13" fill="{sub}">{len(icons)} symbols · 24-unit grid · 1.8 stroke · round caps and joins · currentColor</text>')
        for i, (n, svg) in enumerate(icons.items()):
            attrs, body = inner(svg)
            attrs = re.sub(r'\s+xmlns(:\w+)?="[^"]*"', "", attrs)
            attrs = re.sub(r'\s+(width|height|role|aria-label)="[^"]*"', "", attrs)
            x, y = pad + (i % cols) * cw, y0 + 104 + (i // cols) * chh
            o.append(f'<svg x="{x + 32}" y="{y}" width="40" height="40" color="{fg}"{attrs}>{body}</svg>')
            o.append(f'<text x="{x + 52}" y="{y + 60}" font-size="11" text-anchor="middle" fill="{sub}">{n}</text>')
    o.append("</svg>")
    return "\n".join(o) + "\n"


def docs():
    L = [f"<!-- {HEADER} -->", "# Malva icons", "",
         f"{len(icons)} one-colour symbols, {len(apps)} application pictures and {len(logos)} brand lock-ups.", "",
         "Symbols are drawn on a 24-unit grid with a 1.8 stroke, round caps and joins, and use `currentColor`, so they take the",
         "colour of the text they sit in (CSS), `tint` (Slint `Icon`), or [`svg_with_color`] (Rust). Sizes: 16 / 20 / 24.", "",
         "![icons](../svg/icons-sheet.svg)", "", "## Symbols", "", ", ".join(f"`{n}`" for n in icons), "", "## Application pictures", "",
         ", ".join(f"`{n}`" for n in apps), "", "## Logos", "", ", ".join(f"`{n}`" for n in logos), ""]
    return "\n".join(L)


out("slint/icons.slint", slint())
out("cpp/include/malva/icons.h", cpp())
out("rust/malva-icons/src/gen.rs", rust())
out("svg/icons-sheet.svg", sheet())
out("docs/ICONS.md", docs())
if CHECK:
    if STALE:
        print("out of date: " + ", ".join(STALE))
        sys.exit(1)
    print("icons: all outputs up to date")
else:
    print(f"icons: {len(icons)} symbols, {len(apps)} app pictures, {len(logos)} logos")
