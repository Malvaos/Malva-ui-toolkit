#!/usr/bin/env python3
"""Slint can not loop inside a Path, so charts build their SVG path *string* with a pure function.
This generator unrolls that function for up to N points and writes ui/components/chart-path.slint."""
import os
N=64
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','ui','components','chart-path.slint')
terms=[]
for i in range(1,N):
    terms.append(f'(values.length > {i} ? "L \\{{w * {i} / (values.length - 1)}} \\{{y(values[{i}], h)}} " : "")')
s='''// GENERATED by tools/make-chart-path.py - do not edit.
// Path strings for line/area charts, built from an array of 0..1 values (the first %d points are used).

export global ChartPath {
    pure public function y(v: float, h: float) -> float {
        return (1 - max(0.0, min(1.0, v))) * h;
    }

    /// "M x y L x y ..." for a polyline through `values` spread across width `w`, height `h`.
    pure public function line(values: [float], w: float, h: float) -> string {
        return "M 0 \\{y(values[0], h)} " +
            %s;
    }

    /// The same polyline closed down to the baseline, for a filled area.
    pure public function area(values: [float], w: float, h: float) -> string {
        return line(values, w, h) + "L \\{w} \\{h} L 0 \\{h} Z";
    }
}
''' % (N, ' +\n            '.join(terms))
open(out,'w').write(s); print('wrote',out)
