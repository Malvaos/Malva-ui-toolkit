#!/usr/bin/env python3
"""Writes docs/COMPONENTS.md, the reference of every component the Slint library exports, from the .slint sources
themselves (the `in`, `in-out` and `out` properties and callbacks at the top level of each component, with the
comment above each), so the reference cannot drift from the code.

    python3 tools/gen_components_doc.py            write
    python3 tools/gen_components_doc.py --check    exit 1 if the file on disk differs"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SL = os.path.join(ROOT, "slint")
CHECK = "--check" in sys.argv

GROUPS = [
    ("Foundations", "base.slint", "ControlSize, ForceState, FocusRing, Sizing, Tone"),
    ("Typography", "typography.slint", ""),
    ("Layout", "layout.slint", ""),
    ("Progress", "progress.slint", ""),
    ("Buttons", "button.slint", ""),
    ("Selection controls", "toggle.slint", ""),
    ("Slider", "slider.slint", ""),
    ("Inputs", "inputs.slint", ""),
    ("Navigation", "nav.slint", ""),
    ("Surfaces and small parts", "surface.slint", ""),
    ("Feedback", "feedback.slint", ""),
    ("Menus", "menu.slint", ""),
    ("Dialog", "dialog.slint", ""),
    ("Scrolling", "scroll.slint", ""),
    ("Tooltips", "tooltip.slint", ""),
    ("Windows", "window.slint", ""),
]


def strip_comment(line):
    i = line.find("//")
    return line if i < 0 else line[:i]


def parse(path):
    """Returns [(kind, name, base, doc, members)] for the exported components, structs and enums of a file."""
    lines = open(path).read().split("\n")
    items = []
    i = 0
    while i < len(lines):
        m = re.match(r"export (component|struct|enum|global)\s+(\w+)(?:\s+inherits\s+(\w+))?", lines[i])
        if not m:
            i += 1
            continue
        doc = []
        j = i - 1
        while j >= 0 and lines[j].strip().startswith("//"):
            doc.insert(0, lines[j].strip()[2:].strip())
            j -= 1
        kind, name, base = m.group(1), m.group(2), m.group(3) or ""
        depth = 0
        members, pending = [], []
        k = i
        body = []
        while k < len(lines):
            raw = lines[k]
            code = strip_comment(raw)
            if depth == 1 and kind in ("component", "global"):
                s = code.strip()
                pm = re.match(r"(in-out|in|out)\s+property\s+<([^>]+)>\s+([\w-]+)\s*(?::\s*(.*?))?;?\s*$", s)
                cm = re.match(r"(?:pure\s+)?callback\s+([\w-]+)\s*\(([^)]*)\)\s*(?:->\s*([\w\[\]<>]+))?", s)
                fm = re.match(r"pure\s+public\s+function\s+([\w-]+)\s*\(([^)]*)\)\s*(?:->\s*([\w\[\]<>]+))?|public\s+function\s+([\w-]+)\s*\(([^)]*)\)\s*(?:->\s*([\w\[\]<>]+))?", s)
                if fm:
                    members.append(("function", "", fm.group(1) or fm.group(4), (fm.group(2) if fm.group(1) else fm.group(5)) or "", (fm.group(3) if fm.group(1) else fm.group(6)) or "", " ".join(pending)))
                    pending = []
                elif pm:
                    d = (pm.group(4) or "").rstrip(";")
                    members.append(("property", pm.group(1), pm.group(3), pm.group(2), d, " ".join(pending)))
                    pending = []
                elif cm:
                    members.append(("callback", "", cm.group(1), cm.group(2).strip(), cm.group(3) or "", " ".join(pending)))
                    pending = []
                elif raw.strip().startswith("//"):
                    pending.append(raw.strip()[2:].strip())
                else:
                    pending = []
            elif kind in ("struct", "enum"):
                body.append(code)
            depth += code.count("{") - code.count("}")
            k += 1
            if depth <= 0 and k > i:
                break
        if kind == "enum":
            members = [("value", "", v.strip(), "", "", "") for v in re.split(r",", " ".join(body).split("{", 1)[1].rsplit("}", 1)[0]) if v.strip()]
        elif kind == "struct":
            txt = " ".join(body).split("{", 1)[1].rsplit("}", 1)[0]
            members = [("field", "", a.strip().split(":")[0].strip(), a.split(":", 1)[1].strip() if ":" in a else "", "", "") for a in txt.split(",") if a.strip()]
        items.append((kind, name, base, " ".join(doc), members))
        i = k
    return items


def esc(s):
    return s.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;") if False else s.replace("|", "\\|")


def render():
    out = ["<!-- GENERATED by tools/gen_components_doc.py from slint/components. Do not edit by hand. -->",
           "# Components", "",
           "Every component the Slint library exports, with its public properties and callbacks, taken from the sources. "
           "Import any of them from `malva.slint`:", "",
           "```slint", 'import { Button, ButtonKind, TextField, Toggle, Theme } from "@malva/malva.slint";', "```", "",
           "`in` properties are set by you, `out` properties are read, `in-out` properties do both (use `<=>` to bind one to your own). "
           "Colours, sizes and timings of every component are the kit's tokens, so none of them is a property here; "
           "restyle by changing `tokens/malva-tokens.json`, not a component.", "",
           "The `force` property that most interactive components have (`ForceState`: `none`, `hover`, `pressed`, `focus`) draws a state "
           "without the pointer, for specimens and screenshots.", ""]
    total = 0
    for title, fname, _ in GROUPS:
        items = parse(os.path.join(SL, "components", fname))
        if not items:
            continue
        out += [f"## {title}", ""]
        hdr = []
        for ln in open(os.path.join(SL, "components", fname)).read().split("\n"):
            if ln.startswith("//"):
                hdr.append(ln[2:].strip())
            else:
                break
        if hdr:
            out += [" ".join(hdr), ""]
        for kind, name, base, doc, members in items:
            total += 1
            head = f"### `{name}`" + (f" — {kind}" if kind != "component" else "")
            out += [head, ""]
            if doc:
                out += [doc, ""]
            if kind == "enum":
                out += ["Values: " + ", ".join(f"`{m[2]}`" for m in members), ""]
                continue
            if kind == "struct":
                out += ["| Field | Type |", "|---|---|"] + [f"| `{m[2]}` | `{m[3]}` |" for m in members] + [""]
                continue
            props = [m for m in members if m[0] == "property"]
            cbs = [m for m in members if m[0] == "callback"]
            if props:
                out += ["| Property | | Type | Default | |", "|---|---|---|---|---|"]
                for _, io, n, t, d, note in props:
                    d = d.strip()
                    if len(d) > 40 or io == "out":
                        d = ""
                    d = d.replace("|", "\\|")
                    out.append(f"| `{n}` | {io} | `{t}` | {('`' + d + '`') if d else ''} | {esc(note)} |")
                out.append("")
            if cbs:
                out += ["Callbacks: " + ", ".join(f"`{m[2]}({m[3]})`" + (f" → `{m[4]}`" if m[4] else "") for m in cbs), ""]
            fns = [m for m in members if m[0] == "function"]
            if fns:
                out += ["Functions: " + ", ".join(f"`{m[2]}({m[3]})`" + (f" → `{m[4]}`" if m[4] else "") for m in fns), ""]
            if not props and not cbs and not fns:
                out += [(f"Inherits `{base}`; every property of `{base}` applies." if base else "Takes no properties of its own.") + (" Children go inside it." if base in ("Rectangle", "VerticalLayout", "HorizontalLayout") else ""), ""]
    out.insert(3, f"{total} exported components, structs, enums and globals, in {len(GROUPS)} groups.\n")
    return "\n".join(out).rstrip() + "\n"


text = render()
path = os.path.join(ROOT, "docs", "COMPONENTS.md")
if CHECK:
    if not os.path.exists(path) or open(path).read() != text:
        print("gen_components_doc: docs/COMPONENTS.md is out of date")
        sys.exit(1)
    print("gen_components_doc: up to date")
else:
    open(path, "w").write(text)
    print(f"docs/COMPONENTS.md written ({text.count(chr(10))} lines)")
