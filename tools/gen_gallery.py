#!/usr/bin/env python3
"""Writes gallery/windows.slint: a light and a dark window for every sheet in gallery/sheets.slint.
Each window sets Theme.dark when it is created, which is how a program switches the theme.
    python3 tools/gen_gallery.py"""
import os, re
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
src = open(os.path.join(ROOT, "gallery", "sheets.slint")).read()
sheets = re.findall(r'export component (\w+) inherits Page \{\s*title: "[^"]*";\s*note: "[^"]*";\s*width: (\d+)px;\s*height: (\d+)px;', src)
out = ["// GENERATED by tools/gen_gallery.py. Do not edit by hand.",
       'import { Theme } from "../slint/malva.slint";',
       "import { " + ", ".join(n for n, _, _ in sheets) + ' } from "sheets.slint";', ""]
for n, w, h in sheets:
    for mode in ("Light", "Dark"):
        out.append(f"export component {n}{mode} inherits Window {{\n    width: {w}px;\n    height: {h}px;\n    background: Theme.bg;\n    init => {{\n        Theme.dark = {str(mode == 'Dark').lower()};\n    }}\n    {n} {{\n        width: parent.width;\n        height: parent.height;\n    }}\n}}\n")
open(os.path.join(ROOT, "gallery", "windows.slint"), "w").write("\n".join(out))
print(len(sheets), "sheets:", ", ".join(n for n, _, _ in sheets))
