#!/usr/bin/env python3
"""Builds a tiny stand-in for the `iced` crate, so malva-iced can be type-checked and its tests run without
downloading iced (and without a GPU or a window).

    python3 make_stub.py <path to a checkout of iced 0.14.0> <output directory>
    cargo --config 'patch.crates-io.iced.path="<output directory>"' test --lib --offline   (in rust/malva-iced)

What is in the stub: the style structs and status enums of the widgets that malva-iced styles, EXTRACTED VERBATIM
from the iced source you give it (attributes, doc comments, fields), so a field that does not exist, has another
type, or a missing derive is a compile error here just as it would be against iced. What is hand-written, to the
signatures of the same source (the script checks that each signature is still in the source): Color's constructors,
Theme::custom/palette, Palette, Vector. What is NOT in it: any widget, renderer or runtime, so nothing is drawn
and `examples/gallery.rs` is not built.
"""
import os, re, sys

SRC, OUT = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])


def read(rel):
    return open(os.path.join(SRC, rel)).read()


def extract(rel, kind, name):
    """The text of `pub struct|enum name`, with its doc comments and attributes."""
    text = read(rel)
    lines = text.split("\n")
    start = next((i for i, l in enumerate(lines) if re.match(rf"pub {kind} {name}\b", l)), None)
    if start is None:
        sys.exit(f"{rel}: no `pub {kind} {name}`")
    head = start
    while head > 0 and (lines[head - 1].startswith("///") or lines[head - 1].startswith("#[")):
        head -= 1
    depth, end = 0, None
    for i in range(start, len(lines)):
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0 and ("{" in lines[start] or i > start):
            end = i
            break
    body = [l for l in lines[head:end + 1] if "cfg_attr(feature" not in l]
    return "\n".join(body)


def extract_impl(rel, header):
    """The text of the impl block that starts with `header` (e.g. `impl From<f32> for Radius`)."""
    lines = read(rel).split("\n")
    start = next((i for i, l in enumerate(lines) if l.startswith(header)), None)
    if start is None:
        sys.exit(f"{rel}: no `{header}`")
    depth = 0
    for i in range(start, len(lines)):
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0 and i > start - 1 and "{" in "".join(lines[start:i + 1]):
            return "\n".join(lines[start:i + 1])
    sys.exit("unterminated impl")


def require(rel, signature):
    if signature not in read(rel):
        sys.exit(f"{rel}: the signature `{signature}` is not there any more: update the stub's hand-written part")


# ---- what the hand-written parts are written against
require("core/src/color.rs", "pub const fn from_rgba8(r: u8, g: u8, b: u8, a: f32) -> Color")
require("core/src/color.rs", "    const fn new(r: f32, g: f32, b: f32, a: f32) -> Color")  # private in iced: the stub keeps it private
require("core/src/theme.rs", "pub fn custom(")
require("core/src/theme.rs", "name: impl Into<Cow<'static, str>>,")
require("core/src/theme.rs", "pub fn palette(&self) -> Palette")
require("core/src/vector.rs", "pub const fn new(x: T, y: T) -> Self")

parts = []
parts.append("""// GENERATED by malva-iced/stub/make_stub.py from the iced 0.14.0 source. A type-checking stand-in, not iced.
// The extracted items are copyright their authors and under iced's MIT licence.
#![allow(dead_code, clippy::all)]
use std::borrow::Cow;
use std::sync::Arc;

pub use self::background::Background;
pub use self::border::Border;
pub use self::color::Color;
pub use self::shadow::Shadow;
pub use self::vector::Vector;
pub use self::font::Font;
pub use self::theme_impl::Theme;

pub mod color {
""" + "\n".join("    " + l for l in extract("core/src/color.rs", "struct", "Color").split("\n")) + """

    impl Color {
        pub const BLACK: Color = Color { r: 0.0, g: 0.0, b: 0.0, a: 1.0 };
        pub const WHITE: Color = Color { r: 1.0, g: 1.0, b: 1.0, a: 1.0 };
        pub const TRANSPARENT: Color = Color { r: 0.0, g: 0.0, b: 0.0, a: 0.0 };
        const fn new(r: f32, g: f32, b: f32, a: f32) -> Color { Color { r, g, b, a } }
        pub const fn from_rgba8(r: u8, g: u8, b: u8, a: f32) -> Color {
            Color::new(r as f32 / 255.0, g as f32 / 255.0, b as f32 / 255.0, a)
        }
        pub const fn from_rgb8(r: u8, g: u8, b: u8) -> Color { Color::from_rgba8(r, g, b, 1.0) }
    }
}

pub mod vector {
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
    pub struct Vector<T = f32> { pub x: T, pub y: T }
    impl<T> Vector<T> { pub const fn new(x: T, y: T) -> Self { Self { x, y } } }
}

pub mod shadow {
    use super::{Color, Vector};
""" + "\n".join("    " + l for l in extract("core/src/shadow.rs", "struct", "Shadow").split("\n")) + """
}

pub mod background {
    use super::Color;
    #[derive(Debug, Clone, Copy, PartialEq)]
    pub struct Gradient;
""" + "\n".join("    " + l for l in extract("core/src/background.rs", "enum", "Background").split("\n")).replace("Gradient(Gradient)", "Gradient(Gradient)") + """
    impl From<Color> for Background { fn from(c: Color) -> Self { Background::Color(c) } }
}

pub mod border {
    use super::Color;
""" + "\n".join("    " + l for l in extract("core/src/border.rs", "struct", "Border").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/border.rs", "struct", "Radius").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract_impl("core/src/border.rs", "impl From<f32> for Radius").split("\n")) + "\n"
         + "\n".join("    " + l for l in extract_impl("core/src/border.rs", "impl From<u8> for Radius").split("\n")) + """
}

pub mod font {
    use std::hash::Hash;
""" + "\n".join("    " + l for l in extract("core/src/font.rs", "struct", "Font").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract_impl("core/src/font.rs", "impl Font").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/font.rs", "enum", "Family").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/font.rs", "enum", "Weight").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/font.rs", "enum", "Stretch").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/font.rs", "enum", "Style").split("\n")) + """
}

pub mod theme {
    use super::Color;
""" + "\n".join("    " + l for l in extract("core/src/theme/palette.rs", "struct", "Palette").split("\n")) + "\n\n"
         + "\n".join("    " + l for l in extract("core/src/theme.rs", "struct", "Style").split("\n")) + """
    const fn c(r: f32, g: f32, b: f32) -> Color { Color { r, g, b, a: 1.0 } }
    impl Palette {
        pub const LIGHT: Palette = Palette { background: Color::WHITE, text: Color::BLACK, primary: c(0.35, 0.40, 0.95), success: c(0.07, 0.4, 0.31), warning: c(0.72, 0.49, 0.2), danger: c(0.76, 0.23, 0.22) };
        pub const DARK: Palette = Palette { background: c(0.17, 0.18, 0.19), text: c(0.9, 0.9, 0.9), primary: c(0.35, 0.40, 0.95), success: c(0.07, 0.4, 0.31), warning: c(0.72, 0.49, 0.2), danger: c(0.76, 0.23, 0.22) };
    }
}

mod theme_impl {
    use super::theme::Palette;
    use super::*;
    #[derive(Debug, Clone, PartialEq)]
    pub enum Theme { Light, Dark, Custom(Arc<Custom>) }
    #[derive(Debug, Clone, PartialEq)]
    pub struct Custom { name: String, palette: Palette }
    impl Theme {
        pub fn custom(name: impl Into<Cow<'static, str>>, palette: Palette) -> Self {
            Theme::Custom(Arc::new(Custom { name: name.into().into_owned(), palette }))
        }
        pub fn palette(&self) -> Palette {
            match self { Theme::Light => Palette::LIGHT, Theme::Dark => Palette::DARK, Theme::Custom(c) => c.palette }
        }
    }
}

pub mod overlay {
    pub mod menu {
        use crate::{Background, Border, Color, Shadow};
""" + "\n".join("        " + l for l in extract("widget/src/overlay/menu.rs", "struct", "Style").split("\n")) + """
    }
}

pub mod widget {
    use crate::{border, Background, Border, Color, Shadow};
""")

WIDGETS = {
    "button": ("widget/src/button.rs", [("struct", "Style"), ("enum", "Status")]),
    "checkbox": ("widget/src/checkbox.rs", [("struct", "Style"), ("enum", "Status")]),
    "container": ("widget/src/container.rs", [("struct", "Style")]),
    "pick_list": ("widget/src/pick_list.rs", [("struct", "Style"), ("enum", "Status")]),
    "progress_bar": ("widget/src/progress_bar.rs", [("struct", "Style")]),
    "radio": ("widget/src/radio.rs", [("struct", "Style"), ("enum", "Status")]),
    "rule": ("widget/src/rule.rs", [("struct", "Style"), ("enum", "FillMode")]),
    "scrollable": ("widget/src/scrollable.rs", [("struct", "Style"), ("struct", "Rail"), ("struct", "Scroller"), ("struct", "AutoScroll"), ("enum", "Status")]),
    "slider": ("widget/src/slider.rs", [("struct", "Style"), ("struct", "Rail"), ("struct", "Handle"), ("enum", "HandleShape"), ("enum", "Status")]),
    "svg": ("widget/src/svg.rs", [("struct", "Style"), ("enum", "Status")]),
    "text": ("core/src/widget/text.rs", [("struct", "Style")]),
    "text_editor": ("widget/src/text_editor.rs", [("struct", "Style"), ("enum", "Status")]),
    "text_input": ("widget/src/text_input.rs", [("struct", "Style"), ("enum", "Status")]),
    "toggler": ("widget/src/toggler.rs", [("struct", "Style"), ("enum", "Status")]),
}
for mod, (rel, items) in WIDGETS.items():
    parts.append(f"    pub mod {mod} {{\n        use super::*;")
    for kind, name in items:
        parts.append("\n".join("        " + l for l in extract(rel, kind, name).split("\n")) + "\n")
    if mod == "container":
        parts.append("\n".join("        " + l for l in extract_impl(rel, "impl Default for Style").split("\n")))
    parts.append("    }")
parts.append("}\n\npub mod theme_reexport {}\n")
src = "\n".join(parts)

os.makedirs(os.path.join(OUT, "src"), exist_ok=True)
open(os.path.join(OUT, "Cargo.toml"), "w").write("""[package]
name = "iced"
version = "0.14.0"
edition = "2021"
description = "Type-checking stand-in for iced (see malva-iced/stub/make_stub.py). Not iced."

[features]
default = []
tiny-skia = []
wgpu = []
svg = []
crisp = []
""")
open(os.path.join(OUT, "src", "lib.rs"), "w").write(src)
print("stub written to", OUT, f"({len(src.splitlines())} lines)")
